@tool
def verify_api_files() -> str:
    """
    Verify all required API files exist and are ready.
    """
    try:
        checks = {
            "api/main.py":           os.path.exists("api/main.py"),
            "api/champion_model.pkl": os.path.exists("api/champion_model.pkl"),
        }
        all_ready = all(checks.values())

        return json.dumps({
            "status": "ready" if all_ready else "missing files",
            "files":  checks,
            "next_step": "Run: cd api && uvicorn main:app --reload"
            if all_ready else "Fix missing files first"
        }, indent=2)
    except Exception as e:
        return f"Error: {str(e)}"