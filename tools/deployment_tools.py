# tools/deployment_tools.py
import os
import json
import mlflow
import mlflow.sklearn
import pandas as pd
import numpy as np
from langchain_core.tools import tool
from dotenv import load_dotenv

load_dotenv()


def setup_mlflow():
    mlflow.set_tracking_uri(
        os.getenv("MLFLOW_TRACKING_URI", "sqlite:///mlflow.db")
    )


@tool
def load_champion_model() -> str:
    """
    Load the registered champion model from MLflow Model Registry.
    Saves it locally for the FastAPI server to use.
    Returns model info.
    """
    try:
        setup_mlflow()
        client = mlflow.tracking.MlflowClient()

        model_name = "hospital-readmission-champion"
        versions = client.get_latest_versions(
            model_name, stages=["Staging"]
        )

        if not versions:
            return "No model found in Staging stage."

        version = versions[0]
        model_uri = f"models:/{model_name}/Staging"
        model = mlflow.sklearn.load_model(model_uri)

        # Save model locally for FastAPI to load
        import pickle
        os.makedirs("api", exist_ok=True)
        with open("api/champion_model.pkl", "wb") as f:
            pickle.dump(model, f)

        return json.dumps({
            "status":      "success",
            "model_name":  model_name,
            "version":     version.version,
            "run_id":      version.run_id,
            "saved_to":    "api/champion_model.pkl"
        }, indent=2)
    except Exception as e:
        return f"Error: {str(e)}"


@tool
def get_model_feature_info(dataset_path: str) -> str:
    """
    Get the feature names the model expects as input.
    This is used to generate the API documentation.
    """
    try:
        df = pd.read_csv(dataset_path)
        features = [c for c in df.columns if c != "readmitted"]
        sample_row = df[features].iloc[0].to_dict()

        # Convert numpy types to native Python for JSON serialization
        sample_row = {
            k: float(v) if isinstance(v, (np.floating, np.integer))
            else v
            for k, v in sample_row.items()
        }

        return json.dumps({
            "feature_count": len(features),
            "features":      features,
            "sample_input":  sample_row
        }, indent=2)
    except Exception as e:
        return f"Error: {str(e)}"


